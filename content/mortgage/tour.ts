type Pod = PodEvent["pod"];

const read = (pod: Pod, path: string): Partial<PodEvent> => ({
  kind: "read",
  method: "GET",
  path,
  pod,
  status: 200,
});
const put = (pod: Pod, path: string, status: 201 | 204 = 201): Partial<PodEvent> => ({
  kind: "write",
  method: "PUT",
  path,
  pod,
  status,
});
/** A message or request POSTed to an inbox container. */
const post = (pod: Pod): Partial<PodEvent> => ({
  kind: "write",
  method: "POST",
  path: "/inbox/",
  pod,
  status: 201,
});
/** An access-control document written with at least one new permission. */
const grant = (path: string, status: 201 | 204 = 201): Partial<PodEvent> => ({
  kind: "grant",
  method: "PUT",
  path: `${path}.acl`,
  pod: "alex",
  status,
});
/** An access-control document written with permissions removed and none added. */
const revoke = (path: string): Partial<PodEvent> => ({
  kind: "revoke",
  method: "PUT",
  path: `${path}.acl`,
  pod: "alex",
  status: 204,
});
const note = (kind: AppNote["kind"], org: OrgSlug): Partial<AppNote> => ({ kind, org });

