/**
 * Build-time transform of the wasm-bindgen glue shipped by `@sparq-org/solid-server/wasm` into a
 * factory, `createGlue()`, that returns FRESH bindings on every call.
 *
 * Why: the glue keeps its wasm instance in a module-level variable, and a wasm trap (for example a
 * stack overflow) poisons that instance for every pod in the realm. Recovery needs a new instance
 * with new linear memory, and service workers forbid `import()`, so the glue cannot simply be
 * imported again. Wrapping its source in a function gives a new instance per call. The package
 * file is never modified; the transform fails loudly if the glue's shape changes.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);

/** The names the factory must return; a change upstream fails the build instead of the runtime. */
export const EXPECTED_EXPORTS = [
  "LwsResponse",
  "SolidServer",
  "default",
  "initSync",
  "lwsMemoryCeilingBytes",
  "lwsMemoryLiveBytes",
  "lwsMemoryPeakBytes",
  "lwsSetMemoryCeilingBytes",
  "lws_init",
];

export function gluePath() {
  return require.resolve("@sparq-org/solid-server/wasm");
}

export function wasmPath() {
  return join(dirname(gluePath()), "sparq_lws_wasm_bg.wasm");
}

/** Wrap the glue source in `export function createGlue() { …; return { … } }`. */
export function wrapGlue(source) {
  const names = new Map();
  let body = source.replace(
    /^export (class|function|const|let) ([A-Za-z_$][\w$]*)/gm,
    (_m, kind, name) => {
      names.set(name, name);
      return `${kind} ${name}`;
    },
  );
  body = body.replace(/^export \{([^}]*)\};?\s*$/gm, (_m, list) => {
    for (const part of list.split(",")) {
      const [local, exported] = part.trim().split(/\s+as\s+/);
      if (local) names.set(exported ?? local, local);
    }
    return "";
  });
  if (/^\s*(import|export)\b/m.test(body)) {
    throw new Error(
      "glue-factory: unexpected import/export left in the wasm glue; update the transform",
    );
  }
  body = body.replaceAll("import.meta.url", "__glueBaseUrl");
  const exported = [...names.keys()].sort();
  const missing = EXPECTED_EXPORTS.filter((name) => !names.has(name));
  if (missing.length > 0) {
    throw new Error(`glue-factory: the wasm glue no longer exports ${missing.join(", ")}`);
  }
  const returned = exported.map((name) => `${JSON.stringify(name)}: ${names.get(name)}`).join(", ");
  return [
    "// Generated by packages/pod-runtime/scripts/glue-factory.mjs from @sparq-org/solid-server/wasm.",
    "// Do not edit: rebuild instead.",
    "export function createGlue(__glueBaseUrl) {",
    body,
    `return { ${returned} };`,
    "}",
    "",
  ].join("\n");
}

const DTS = `// Generated by packages/pod-runtime/scripts/glue-factory.mjs. Do not edit.
export type Glue = typeof import("@sparq-org/solid-server/wasm");
/** Fresh wasm-bindgen bindings (and, once initialised, a fresh wasm instance) per call. */
export function createGlue(baseUrl?: string): Glue;
`;

/** Write the factory next to the sources (for tsc, Vite and Vitest) and into dist/. */
export function writeGlueFactory(packageDir) {
  const js = wrapGlue(readFileSync(gluePath(), "utf8"));
  for (const dir of [join(packageDir, "src", "generated"), join(packageDir, "dist", "generated")]) {
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "glue-factory.js"), js);
    writeFileSync(join(dir, "glue-factory.d.ts"), DTS);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeGlueFactory(join(dirname(fileURLToPath(import.meta.url)), ".."));
  console.log("glue-factory: wrote src/generated and dist/generated");
}
